function tx(
  en: string,
  partial: Partial<CompleteTranslations> = {},
): CompleteTranslations {
  return Object.fromEntries(
    scanMenuLanguages.map((language) => [
      language.code,
      partial[language.code] ?? phraseTranslations[en]?.[language.code] ?? en,
    ]),
  ) as CompleteTranslations;
}

function ingredient(
  id: string,
  category: IngredientCategory,
  en: string,
  partial: Partial<CompleteTranslations> = {},
  allergens: string[] = [],
): IngredientTaxonomyItem {
  return { id, category, allergens, translations: tx(en, partial) };
}

function modifier(
  id: string,
  type: ModifierTaxonomyItem["type"],
  en: string,
  ingredientId?: string,
  partial: Partial<CompleteTranslations> = {},
): ModifierTaxonomyItem {
  return { id, type, ingredientId, translations: tx(en, partial) };
}

function allergen(
  id: string,
  en: string,
  partial: Partial<CompleteTranslations> = {},
): AllergenTaxonomyItem {
  return { id, translations: tx(en, partial) };
}

