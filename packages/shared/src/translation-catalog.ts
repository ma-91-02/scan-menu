export function pickCatalogTranslation(
  translations: CompleteTranslations,
  language: string,
) {
  return translations[language as ScanMenuLanguageCode] ?? translations.en;
}

export function getUiTranslationMap(language: string): LocalizedTranslationMap {
  return Object.fromEntries(
    uiTranslations.map((item) => [
      item.key,
      pickCatalogTranslation(item.translations, language),
    ]),
  );
}

export function getRestaurantPageCopy(
  language: string,
): LocalizedTranslationMap {
  const uiMap = getUiTranslationMap(language);
  return Object.fromEntries(
    restaurantPageTranslationKeys.map((key) => [key, uiMap[key] ?? key]),
  );
}
