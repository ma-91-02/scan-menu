export function searchCurrencyCodes(query: string, language: string) {
  const value = normalizeSearch(query);
  if (!value) return fallbackCurrencyCodes;
  return fallbackCurrencyCodes.filter((code) =>
    currencySearchNames(code, language).some((name) =>
      normalizeSearch(name).includes(value),
    ),
  );
}

export function currencyLabel(code: string, language = "en") {
  const name =
    currencyDisplayNames[code]?.[language] ??
    currencyDisplayNames[code]?.en ??
    currencyDisplayNames[code]?.ar;
  return name ? `${code} - ${name}` : code;
}

function currencySearchNames(code: string, language: string) {
  const names = currencyDisplayNames[code] ?? {};
  return [
    code,
    names[language],
    names.en,
    names.ar,
    ...Object.values(names),
  ].filter(Boolean) as string[];
}

function normalizeSearch(value: string) {
  return value
    .trim()
    .toLowerCase()
    .replace(/[إأآا]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/\bال(?=\p{Letter})/gu, "")
    .replace(/[^\p{Letter}\p{Number}]+/gu, " ");
}
